"""Generate Mermaid architecture diagram documentation for the LangGraph StateGraph.

Outputs to docs/graph.md.
"""

import sys
from pathlib import Path

# Ensure backend root is on sys.path
backend_root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(backend_root))

from app.core.graph import build_extraction_subgraph, build_knowledge_graph  # noqa: E402


def generate_graph_docs() -> None:
    repo_root = backend_root.parent
    docs_file = repo_root / "docs" / "graph.md"

    knowledge_graph = build_knowledge_graph().compile()
    extraction_subgraph = build_extraction_subgraph().compile()

    k_mermaid = knowledge_graph.get_graph().draw_mermaid()
    e_mermaid = extraction_subgraph.get_graph().draw_mermaid()

    content = f"""# LangGraph Query Flow & Extraction Subgraph Topology

Automated Mermaid diagram generated by `scripts/generate_graph_docs.py`.
Verified by contract tests in `backend/tests/unit/test_graph_contracts.py`.

## 1. 9-Node Knowledge Query StateGraph

```mermaid
{k_mermaid}
```

## 2. Dedicated Extraction Subgraph

```mermaid
{e_mermaid}
```
"""

    docs_file.write_text(content.replace("\r\n", "\n"), encoding="utf-8", newline="\n")
    print(f"Graph documentation successfully written to {docs_file}")


if __name__ == "__main__":
    generate_graph_docs()
